# -*- coding: utf-8 -*-
"""Build a dependency-free Windows desktop-pet package from the command line.

This is the CLI twin of the browser customiser (web/export.js). It produces the
same ZIP layout, so a pet can be generated without a browser or a server.

    python scripts/make_bat_pack.py --name 团子 --species cat --out dist/my-pet.zip
    python scripts/make_bat_pack.py --photo my-cat.jpg --name 咪咪 --out dist/mimi.zip
"""
from __future__ import annotations

import argparse
import json
import zipfile
from io import BytesIO
from pathlib import Path

from PIL import Image

HERE = Path(__file__).resolve().parent
SKILL_ROOT = HERE.parent
PET_DIR = SKILL_ROOT / "assets" / "pet"

SPRITES = {
    "cat":        ["cat_idle", "cat_walk", "cat_stretch", "cat_groom", "cat_sleep"],
    "orange":     ["orange_idle", "cat_walk", "cat_stretch", "cat_groom", "orange_sleep"],
    "dog":        ["dog_idle", "dog_walk", "dog_stretch", "dog_groom", "dog_sleep"],
    "rabbit":     ["rabbit_idle", "rabbit_walk", "rabbit_stretch", "rabbit_groom", "rabbit_sleep"],
    "chinchilla": ["chinchilla_idle", "chinchilla_walk", "chinchilla_stretch", "chinchilla_groom", "chinchilla_sleep"],
    "hamster":    ["hamster_idle", "hamster_walk", "hamster_stretch", "hamster_groom", "hamster_sleep"],
    "bird":       ["bird_idle", "bird_walk", "bird_stretch", "bird_groom", "bird_sleep"],
}

DEFAULT_LINES = ["在呢，一直都在。", "今天也要好好工作呀～", "摸摸我就有精神啦！", "别忘了喝水哦。"]

START_BAT = """@echo off
title Wangzai Desktop Pet
cd /d "%~dp0"
powershell.exe -NoProfile -ExecutionPolicy Bypass -File "%~dp0win_pet.ps1"
if errorlevel 1 (
  echo.
  echo Something went wrong. Make sure the whole zip was extracted first.
  pause
)
"""

README_TXT = """望崽宠乐园 · 使用说明
========================================

1. 请先【解压整个压缩包】，不要直接在压缩软件里双击运行。
2. 双击 "start.bat"，你的桌宠就会出现在屏幕右下角。
3. 左键拖动它、双击摸摸它、右键可以换动作 / 散步 / 置顶 / 退出。
4. 想改名字、大小、速度、台词，用记事本打开 pet-config.json 修改后保存，
   再重新双击 start.bat 即可生效。
5. 想换形象，把新的 PNG 放进 assets\\pet\\ 目录（背景需为纯洋红 #FF00FF）。
6. 想开机自动陪伴：给 start.bat 建一个快捷方式，放进
   %APPDATA%\\Microsoft\\Windows\\Start Menu\\Programs\\Startup

完全离线运行：不需要 Python、不需要安装任何软件、不联网、不上传照片。

本包由「望崽宠乐园 · 免费定制」生成，可自由分享给朋友。
"""


def magenta_key(im: Image.Image, max_side: int = 320) -> Image.Image:
    """Binarise alpha onto a #FF00FF background for WinForms TransparencyKey."""
    src = im.convert("RGBA")
    src.thumbnail((max_side, max_side), Image.LANCZOS)
    out = Image.new("RGB", src.size, (255, 0, 255))
    sp, dp = src.load(), out.load()
    for y in range(src.height):
        for x in range(src.width):
            r, g, b, a = sp[x, y]
            if a >= 128:
                dp[x, y] = (r, g, b)
    return out


def sticker(path: Path, side: int = 320) -> Image.Image:
    """Soft circular sticker from a visitor's own photo."""
    im = Image.open(path).convert("RGB")
    crop = min(im.size)
    im = im.crop(((im.width - crop) // 2, (im.height - crop) // 2,
                  (im.width + crop) // 2, (im.height + crop) // 2))
    im = im.resize((side, side), Image.LANCZOS).convert("RGBA")
    grad = Image.radial_gradient("L").resize((side, side))
    mask = grad.point(lambda v: 255 if v < 205 else max(0, int((255 - v) * 255 / 50)))
    bg = Image.new("RGBA", (side, side), (255, 0, 255, 255))
    bg.paste(im, (0, 0), mask)
    return bg


def png_bytes(im: Image.Image) -> bytes:
    buf = BytesIO()
    im.save(buf, "PNG")
    return buf.getvalue()


def build(args) -> Path:
    cfg = {
        "name": args.name,
        "species": "my" if args.photo else args.species,
        "size": args.size,
        "speed": args.speed,
        "auto": not args.no_auto,
        "topmost": not args.no_topmost,
        "lines": (args.line or DEFAULT_LINES)[:12],
        "note": "Generated by wangzai-pet skill",
    }
    ps1 = (HERE / "win_pet.ps1").read_bytes()
    if not ps1.startswith(b"\xef\xbb\xbf"):
        ps1 = b"\xef\xbb\xbf" + ps1

    files = [
        ("pet-config.json", json.dumps(cfg, ensure_ascii=False, indent=2).encode("utf-8")),
        ("win_pet.ps1", ps1),
        ("start.bat", START_BAT.encode("ascii")),
        ("README.txt", b"\xef\xbb\xbf" + README_TXT.encode("utf-8")),
    ]

    if args.photo:
        files.append(("assets/pet/my-pet.png", png_bytes(magenta_key(sticker(Path(args.photo))))))
    else:
        for name in dict.fromkeys(SPRITES.get(args.species, SPRITES["cat"])):
            src = PET_DIR / f"{name}.png"
            if not src.exists():
                continue
            files.append((f"assets/pet/{name}.png", png_bytes(magenta_key(Image.open(src)))))

    if not any(f[0].startswith("assets/pet/") for f in files):
        raise SystemExit("No sprites found. Check assets/pet/ or pass --photo.")

    out = Path(args.out).resolve()
    out.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(out, "w", zipfile.ZIP_STORED) as z:
        for name, data in files:
            z.writestr(name, data)
    return out


def main() -> None:
    ap = argparse.ArgumentParser(description="Build a zero-dependency Windows desktop-pet ZIP")
    ap.add_argument("--name", default="望崽")
    ap.add_argument("--species", default="cat", choices=sorted(SPRITES))
    ap.add_argument("--size", type=int, default=220)
    ap.add_argument("--speed", type=int, default=2)
    ap.add_argument("--line", action="append", help="custom line (repeatable)")
    ap.add_argument("--photo", help="path to a pet photo; makes a circular sticker")
    ap.add_argument("--no-auto", action="store_true")
    ap.add_argument("--no-topmost", action="store_true")
    ap.add_argument("--out", default="dist/my-pet.zip")
    args = ap.parse_args()
    out = build(args)
    with zipfile.ZipFile(out) as z:
        names = z.namelist()
        bad = z.testzip()
    print(f"OK  {out}  ({out.stat().st_size} bytes, {len(names)} files)")
    print("    " + ", ".join(names))
    if bad:
        raise SystemExit(f"ZIP integrity failed: {bad}")


if __name__ == "__main__":
    main()
